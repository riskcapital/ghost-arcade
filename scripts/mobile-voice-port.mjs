#!/usr/bin/env node
// Brings the desktop's visual voice shaders (public/ISF/VX-*.fs) onto the phone
// from a git ref, byte for byte, so the phone's copies never drift from the
// desktop's. The chosen set, its names and the commit it came from live in
// native-mobile/studio-voices.json; the phone's catalog entries are generated
// from it into src/lib/mobile/studioVoiceList.ts.
//
//   node scripts/mobile-voice-port.mjs [--ref <ref>]
//     Copy the chosen set from <ref> (default: the ref in studio-voices.json),
//     remove voice files that are no longer chosen, record the commit, and
//     regenerate the catalog. Names come from the ref's voice catalog.
//   node scripts/mobile-voice-port.mjs --all [--ref <ref>]
//     Copy every voice the ref has, for benching candidates. Nothing is recorded.
//   node scripts/mobile-voice-port.mjs --check
//     Fail when a chosen file differs from the recorded commit's copy.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, rmSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const recordFile = join(root, 'native-mobile/studio-voices.json');
const catalogFile = join(root, 'src/lib/mobile/studioVoiceList.ts');
const folder = join(root, 'public/ISF');
const arg = (name) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : undefined; };
const record = JSON.parse(readFileSync(recordFile, 'utf8'));
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 64 << 20 });
const gitBytes = (...args) => execFileSync('git', args, { cwd: root, maxBuffer: 64 << 20 });

if (process.argv.includes('--check')) {
  let bad = 0;
  for (const v of record.voices) {
    const want = gitBytes('show', `${record.sha}:public/ISF/${v.file}`);
    const have = existsSync(join(folder, v.file)) ? readFileSync(join(folder, v.file)) : null;
    if (!have || !want.equals(have)) { console.log(`DIFFERS ${v.file}`); bad++; }
  }
  console.log(bad ? `${bad} of ${record.voices.length} voices differ from ${record.sha.slice(0, 8)}.` : `All ${record.voices.length} voices match ${record.sha.slice(0, 8)}.`);
  process.exit(bad ? 1 : 0);
}

const ref = arg('--ref') ?? record.ref;
const sha = git('rev-parse', '--verify', `${ref}^{commit}`).trim();
const available = git('ls-tree', '--name-only', `${sha}:public/ISF`).split('\n').filter((f) => /^VX-.*\.fs$/.test(f));

if (process.argv.includes('--all')) {
  for (const file of available) writeFileSync(join(folder, file), gitBytes('show', `${sha}:public/ISF/${file}`));
  console.log(`Copied all ${available.length} voices from ${ref} (${sha.slice(0, 8)}) for benching. Nothing recorded; run without --all to keep only the chosen set.`);
  process.exit(0);
}

// Names as the desktop shows them (its voice catalog), falling back to the file name.
const names = new Map();
try {
  const catalog = git('show', `${sha}:src/lib/music/visualScenes.ts`);
  for (const m of catalog.matchAll(/\{\s*file:\s*'(VX-[^']+\.fs)',\s*name:\s*'([^']+)'/g)) names.set(m[1], m[2]);
} catch { /* an older ref without the catalog */ }
const spaced = (file) => file.replace(/^VX-|\.fs$/g, '').replace(/([a-z])([A-Z])/g, '$1 $2');

const missing = record.voices.filter((v) => !available.includes(v.file));
if (missing.length) throw new Error(`${ref} has no ${missing.map((v) => v.file).join(', ')}.`);
const chosen = new Set(record.voices.map((v) => v.file));
for (const v of record.voices) {
  writeFileSync(join(folder, v.file), gitBytes('show', `${sha}:public/ISF/${v.file}`));
}
// A name in the record is the phone's own (where the desktop's would repeat a library name).
const nameOf = (v) => v.name ?? names.get(v.file) ?? spaced(v.file);
// Voice files are this script's: any not chosen is removed (a bench run with --all leaves them).
let removed = 0;
for (const file of readdirSync(folder)) if (/^VX-.*\.fs$/.test(file) && !chosen.has(file)) { rmSync(join(folder, file)); removed++; }

record.ref = ref;
record.sha = sha;
record.copied = new Date().toISOString().slice(0, 10);
writeFileSync(recordFile, JSON.stringify(record, null, 2) + '\n');

const id = (file) => 'voice-' + file.replace(/^VX-|\.fs$/g, '').replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const entries = record.voices.map((v) => {
  const entry = { id: id(v.file), path: `ISF/${v.file}`, name: nameOf(v), category: 'studio', audioNative: true, voice: true, motion: { flow: 0, breath: 0, glow: false } };
  // The phone plays a voice all the time; "comes and goes with its sound" stays an option.
  const defaults = { vxAuto: false, ...(v.source !== undefined ? { vxSource: v.source } : {}), ...(v.defaults ?? {}) };
  return { ...entry, defaults };
});
writeFileSync(catalogFile, `// Generated by scripts/mobile-voice-port.mjs from native-mobile/studio-voices.json.
// The voices are the desktop's visual voice shaders, copied byte for byte from ${sha.slice(0, 8)}.
import type { MobileShader } from './standaloneShaderList';

export const STUDIO_VOICE_SHADERS: MobileShader[] = ${JSON.stringify(entries, null, 2)};
`);
console.log(`Copied ${record.voices.length} voices from ${ref} (${sha.slice(0, 8)}); removed ${removed} not chosen. Catalog: ${catalogFile.slice(root.length + 1)}.`);

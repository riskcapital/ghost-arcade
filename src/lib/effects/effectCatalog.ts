export const EFFECT_CATALOG: EffectCatalogEntry[] = RAW_CATALOG.map(entry => ({
  ...entry,
  tier: getEffectTier(entry.category),
}));

// Helper to get all unique categories in order
export function getEffectCategories(): string[] {
  const seen = new Set<string>();
  const cats: string[] = [];
  for (const entry of EFFECT_CATALOG) {
    if (!seen.has(entry.category)) {
      seen.add(entry.category);
      cats.push(entry.category);
    }
  }
  return cats;
}
